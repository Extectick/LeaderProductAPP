const { getDefaultConfig } = require('expo/metro-config');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const config = getDefaultConfig(__dirname);
config.maxWorkers = 2;
config.watchFolders = [root];
config.resolver.nodeModulesPaths = [path.join(root, 'node_modules')];
config.resolver.blockList = [/[/\\](?:\.cxx|\.gradle|tmp|dev-builds|dist-help-android|dist-help-web|output)[/\\]/,/[/\\]android[/\\](?:app[/\\])?build[/\\]/];
config.resolver.resolveRequest = (context, moduleName, platform) => context.resolveRequest(context, moduleName.startsWith('@/') ? path.join(root, moduleName.slice(2)) : moduleName, platform);
module.exports = config;
